/// Non-secret establishment binding captured from a launch before TLS.
///
/// The binding carries exactly the values the `Establish` echo must contain:
/// the verified component identity, the four launch/channel nonces, and both
/// leaf certificate digests. It never carries key material. Build it with
/// [`LaunchBinding::from_prepared`] before calling
/// [`PreparedLaunch::establish`](super::PreparedLaunch::establish), because
/// establishment consumes the launch material.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LaunchBinding {
    identity: super::LaunchIdentity,
    core_instance_nonce: Nonce,
    launch_nonce: SessionId,
    control_channel_nonce: Nonce,
    data_channel_nonce: Nonce,
    core_leaf_digest: Digest,
    helper_leaf_digest: Digest,
}

impl LaunchBinding {
    /// Build the establishment binding from trusted launch inputs.
    ///
    /// The typed nonces keep the three 32-byte launch/channel values apart;
    /// the caller must pass values generated by the launch, not values derived
    /// from a peer record.
    #[must_use]
    pub fn new(
        identity: super::LaunchIdentity,
        core_instance_nonce: Nonce,
        launch_nonce: SessionId,
        control_channel_nonce: Nonce,
        data_channel_nonce: Nonce,
        core_leaf_digest: Digest,
        helper_leaf_digest: Digest,
    ) -> Self {
        Self {
            identity,
            core_instance_nonce,
            launch_nonce,
            control_channel_nonce,
            data_channel_nonce,
            core_leaf_digest,
            helper_leaf_digest,
        }
    }

    /// Snapshot the non-secret binding from a prepared launch.
    ///
    /// # Errors
    ///
    /// Returns [`PublicationControlError::LaunchMaterialConsumed`] after
    /// [`PreparedLaunch::establish`](super::PreparedLaunch::establish) has
    /// consumed the material, or
    /// [`PublicationControlError::Record`] when the identity violates a named
    /// manifest bound.
    pub fn from_prepared(launch: &super::PreparedLaunch) -> Result<Self, PublicationControlError> {
        let core_leaf_digest = launch
            .core_cert_sha256()
            .ok_or(PublicationControlError::LaunchMaterialConsumed)?;
        let helper_leaf_digest = launch
            .helper_cert_sha256()
            .ok_or(PublicationControlError::LaunchMaterialConsumed)?;
        let binding = Self::new(
            launch.identity().clone(),
            Nonce::new(*launch.core_instance_nonce()),
            SessionId::new(*launch.launch_nonce()),
            Nonce::new(*launch.control_channel_nonce()),
            Nonce::new(*launch.data_channel_nonce()),
            Digest::new(core_leaf_digest),
            Digest::new(helper_leaf_digest),
        );
        // Reject an identity or nonce width the contract cannot encode before
        // the caller writes the bootstrap record or starts the helper.
        binding.probe_establish()?;
        Ok(binding)
    }

    /// Launch nonce that binds every control record header.
    #[must_use]
    pub const fn launch_nonce(&self) -> SessionId {
        self.launch_nonce
    }

    /// Exact non-secret echo expected from the helper.
    fn expected_echo(&self) -> EstablishmentEcho {
        EstablishmentEcho {
            bootstrap_format_version: BOOTSTRAP_FORMAT_VERSION,
            control_protocol_version: CONTROL_PROTOCOL_VERSION,
            core_instance_nonce: self.core_instance_nonce,
            launch_nonce: self.launch_nonce,
            component_name: self.identity.component_name().to_owned(),
            descriptor_version: self.identity.descriptor_version().to_owned(),
            executable_name: self.identity.executable_name().to_owned(),
            executable_sha256: Digest::new(*self.identity.executable_sha256()),
            component_protocol_version: self.identity.component_protocol_version(),
            control_channel_nonce: self.control_channel_nonce,
            data_channel_nonce: self.data_channel_nonce,
            delegation_purpose: DELEGATION_PURPOSE.to_owned(),
            control_profile: CONTROL_PROFILE.to_owned(),
            key_material_profile: KEY_MATERIAL_PROFILE,
            key_type: KEY_TYPE_ECDSA_P256,
            core_leaf_digest: self.core_leaf_digest,
            helper_leaf_digest: self.helper_leaf_digest,
        }
    }

    /// Encode a throwaway `Establish` record to validate the binding.
    fn probe_establish(&self) -> Result<(), PublicationControlError> {
        ControlRecord {
            sender: Sender::Core,
            sequence: 1,
            session_id: self.launch_nonce,
            body: RecordBody::Establish(self.expected_echo()),
        }
        .encode()
        .map_err(PublicationControlError::Record)?;
        Ok(())
    }
}

/// Read-only Core metadata source view adopted from one authenticated feed.
///
/// The view is immutable and can only be produced by
/// [`PublicationControl`] after canonical parse and digest validation. It
/// exposes the shared pure projection type, so callers never receive a second
/// metadata schema.
pub struct MetadataView {
    projection: ProviderRoutingProjection,
    canonical: Vec<u8>,
    digest: Digest,
    feed_revision: u64,
}

impl MetadataView {
    /// Feed revision announced with this projection.
    #[must_use]
    pub const fn feed_revision(&self) -> u64 {
        self.feed_revision
    }

    /// SHA-256 over the exact canonical projection bytes.
    #[must_use]
    pub const fn digest(&self) -> Digest {
        self.digest
    }

    /// Exact canonical UTF-8 projection bytes.
    #[must_use]
    pub fn canonical_bytes(&self) -> &[u8] {
        &self.canonical
    }

    /// Sorted provider groups in the adopted projection.
    #[must_use]
    pub fn providers(&self) -> &[ProviderEntry] {
        self.projection.providers()
    }

    /// The shared pure projection value.
    #[must_use]
    pub const fn projection(&self) -> &ProviderRoutingProjection {
        &self.projection
    }
}

impl fmt::Debug for MetadataView {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("MetadataView")
            .field("feed_revision", &self.feed_revision)
            .field("providers", &self.projection.providers().len())
            .field("canonical_len", &self.canonical.len())
            .field("digest", &self.digest)
            .finish()
    }
}

/// Lifecycle phase of one Core control driver.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ControlPhase {
    /// No `Establish` has been sent.
    Unestablished,
    /// A lifetime is current and one projection is expected.
    AwaitProjection,
    /// A projection was adopted and one publication tuple is pending.
    Ready,
    /// `Publish` was sent and one `Ack` is expected.
    AwaitAck,
    /// `Ack` was accepted and `Bind` may be sent.
    AckAccepted,
    /// `Bind` was sent and one `Bound` is expected.
    AwaitBound,
    /// `Bound` was accepted and one receipt is retained.
    Bound,
    /// Authority was invalidated locally or by the helper; a `Lifetime` is
    /// expected unless the withdrawal was terminal.
    AwaitLifetime,
    /// Authority is revoked; no further record is sent or accepted.
    Closed,
}

impl ControlPhase {
    const fn label(self) -> &'static str {
        match self {
            Self::Unestablished => "unestablished",
            Self::AwaitProjection => "await-projection",
            Self::Ready => "ready",
            Self::AwaitAck => "await-ack",
            Self::AckAccepted => "ack-accepted",
            Self::AwaitBound => "await-bound",
            Self::Bound => "bound",
            Self::AwaitLifetime => "await-lifetime",
            Self::Closed => "closed",
        }
    }
}

impl fmt::Display for ControlPhase {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.label())
    }
}

/// Why the Core revoked provider-publication authority.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RevocationReason {
    /// The control stream closed or failed.
    ControlTransport,
    /// A peer record violated the control contract or record order.
    ProtocolViolation,
    /// The establishment echo did not match the launch binding.
    EstablishmentMismatch,
    /// The peer reported a terminal control error.
    PeerError,
    /// The peer or a local shutdown withdrew authority.
    PeerWithdrewAuthority,
    /// A bounded resource or the publication version space was exhausted.
    ResourceLimit,
    /// The caller closed the driver locally.
    LocalClose,
}

/// One successful driver step that changed observable state.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ControlEvent {
    /// A projection was adopted and a fresh publication tuple allocated.
    ProjectionAdopted {
        /// Current helper lifetime.
        lifetime_id: LifetimeId,
        /// Registry feed revision.
        feed_revision: u64,
        /// Core-minted R1 source-view snapshot version.
        snapshot_version: u64,
        /// Fresh Core publication version (in the tuple's publication identity).
        publication_version: u64,
    },
    /// The exact pending publication was acknowledged.
    PublicationAcknowledged {
        /// Fresh helper acknowledgement identifier.
        ack_id: AckId,
    },
    /// The exact pending publication was bound.
    PublicationBound {
        /// Exact bound tuple.
        tuple: Tuple,
        /// Retained helper proof receipt.
        receipt: ReceiptId,
    },
    /// The current lifetime was invalidated.
    Invalidated {
        /// Invalidated lifetime.
        lifetime_id: LifetimeId,
        /// Invalidated feed revision.
        feed_revision: u64,
        /// Closed invalidation reason.
        reason: Reason,
        /// `true` when this record only correlated a crossed invalidation and
        /// changed no authority.
        correlation_only: bool,
    },
    /// A fresh lifetime replaced the invalidated predecessor.
    LifetimeRotated {
        /// Immediately retired predecessor.
        previous: LifetimeId,
        /// New current lifetime.
        lifetime_id: LifetimeId,
        /// Feed revision announced with the new lifetime.
        feed_revision: u64,
    },
    /// The peer withdrew authority with grant loss or shutdown.
    AuthorityClosed {
        /// Closed withdrawal reason.
        reason: Reason,
    },
}

/// Fail-closed Core publication-control rejection.
///
/// `Display` uses fixed text and never includes a payload, model string,
/// identifier, path, or secret. [`std::error::Error::source`] exposes the
/// structured framing or codec cause for local diagnostics.
#[derive(Debug)]
pub enum PublicationControlError {
    /// This platform has no authenticated publication-control transport.
    UnsupportedPlatform,
    /// The framed transport rejected a byte stream or control record.
    Transport(ControlIoError),
    /// The pure record contract rejected an encoding or field.
    Record(ControlError),
    /// The launch material was already consumed by establishment.
    LaunchMaterialConsumed,
    /// The establishment echo differed from the launch binding.
    EstablishmentMismatch {
        /// Fixed field label.
        field: &'static str,
    },
    /// The record session identifier differs from the launch nonce.
    SessionMismatch,
    /// The per-direction sequence is not the exact next value.
    SequenceMismatch,
    /// The record sender is not the authenticated helper role.
    UnexpectedSender {
        /// Received sender role.
        sender: Sender,
    },
    /// The record kind is not valid in the current phase.
    UnexpectedRecord {
        /// Received record kind.
        kind: Kind,
        /// Current driver phase.
        phase: ControlPhase,
    },
    /// The lifetime, revision, tuple, or acknowledgement is not current.
    StaleAuthority,
    /// A new lifetime identifier was zero, repeated, or already retired.
    ///
    /// Fresh random identifiers are rejected when they are all-zero or repeat
    /// an identifier Core can still observe.
    LifetimeNotFresh,
    /// An acknowledgement or receipt identifier was zero or repeated.
    ///
    /// Fresh random identifiers are rejected when they are all-zero or repeat
    /// an identifier Core can still observe.
    IdentifierNotFresh,
    /// The helper reported a terminal control error.
    PeerError {
        /// Closed peer error code.
        code: ErrorCode,
    },
    /// The helper withdrew authority with grant loss or shutdown.
    PeerWithdrewAuthority {
        /// Closed withdrawal reason.
        reason: Reason,
    },
    /// Core may not originate this invalidation reason.
    HelperOwnedInvalidationReason {
        /// Refused reason.
        reason: Reason,
    },
    /// A sequence or publication version space is exhausted.
    VersionExhausted,
    /// The requested step is not valid in the current phase; nothing was sent.
    NotReady {
        /// Current driver phase.
        phase: ControlPhase,
    },
    /// A publication transaction is in flight; invalidate after it completes.
    Busy {
        /// Current driver phase.
        phase: ControlPhase,
    },
    /// Authority is revoked; the driver accepts no further work.
    Closed,
}

impl fmt::Display for PublicationControlError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsupportedPlatform => {
                formatter.write_str("publication control is unsupported on this platform")
            }
            Self::Transport(_) => formatter.write_str("control transport rejected"),
            Self::Record(_) => formatter.write_str("control record rejected"),
            Self::LaunchMaterialConsumed => {
                formatter.write_str("launch material was consumed before the binding snapshot")
            }
            Self::EstablishmentMismatch { field } => {
                write!(
                    formatter,
                    "establishment echo differs from the launch binding at {field}"
                )
            }
            Self::SessionMismatch => {
                formatter.write_str("control session differs from the launch nonce")
            }
            Self::SequenceMismatch => {
                formatter.write_str("control sequence is not the exact next value")
            }
            Self::UnexpectedSender { .. } => {
                formatter.write_str("control record sender is not the authenticated helper")
            }
            Self::UnexpectedRecord { .. } => {
                formatter.write_str("control record is not valid in the current phase")
            }
            Self::StaleAuthority => {
                formatter.write_str("control lifetime or feed revision is not current")
            }
            Self::LifetimeNotFresh => {
                formatter.write_str("control lifetime identifier is not fresh")
            }
            Self::IdentifierNotFresh => {
                formatter.write_str("control acknowledgement or receipt is not fresh")
            }
            Self::PeerError { code } => formatter.write_str(code.diagnostic()),
            Self::PeerWithdrewAuthority { .. } => {
                formatter.write_str("peer withdrew provider-publication authority")
            }
            Self::HelperOwnedInvalidationReason { .. } => {
                formatter.write_str("Core may not originate this invalidation reason")
            }
            Self::VersionExhausted => formatter.write_str("control version space exhausted"),
            Self::NotReady { .. } => {
                formatter.write_str("control driver is not ready for this step")
            }
            Self::Busy { .. } => {
                formatter.write_str("a publication transaction is already in flight")
            }
            Self::Closed => formatter.write_str("provider-publication authority is closed"),
        }
    }
}

impl std::error::Error for PublicationControlError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Transport(error) => Some(error),
            Self::Record(error) => Some(error),
            _ => None,
        }
    }
}

