/// First Core publication version minted for the initial adopted projection.
const INITIAL_PUBLICATION_VERSION: u64 = 1;

/// First R1 source-view snapshot version minted for the initial adopted
/// projection.
const INITIAL_SOURCE_VIEW_VERSION: u64 = 1;

/// Core-side provider-publication control driver.
///
/// `T` is any [`ControlRecordIo`] implementation; production uses
/// [`AuthenticatedControl`], tests use an in-memory peer. The driver owns the
/// transport and drops it on revocation, so a revoked session cannot be
/// reused or attached to a replacement stream.
pub struct PublicationControl<T> {
    io: Option<T>,
    binding: LaunchBinding,
    expected_echo: EstablishmentEcho,
    phase: ControlPhase,
    in_sequence: u64,
    out_sequence: u64,
    lifetime: Option<LifetimeId>,
    feed_revision: Option<u64>,
    view: Option<MetadataView>,
    pending: Option<PendingPublication>,
    receipt: Option<ActiveReceipt>,
    retirement: Option<RetiredLifetime>,
    retirement_crossed: bool,
    invalidation: Option<InvalidationWait>,
    retired_receipt: Option<ReceiptId>,
    snapshot_version: Option<u64>,
    next_version: u64,
    next_snapshot_version: u64,
    revocation: Option<RevocationReason>,
}

impl<T: ControlRecordIo> PublicationControl<T> {
    /// Build one driver over an authenticated transport and launch binding.
    ///
    /// # Errors
    ///
    /// Returns [`PublicationControlError::Record`] when the binding cannot be
    /// encoded, before any record is sent.
    pub fn new(io: T, binding: LaunchBinding) -> Result<Self, PublicationControlError> {
        let expected_echo = binding.expected_echo();
        binding.probe_establish()?;
        Ok(Self {
            io: Some(io),
            binding,
            expected_echo,
            phase: ControlPhase::Unestablished,
            in_sequence: 0,
            out_sequence: 0,
            lifetime: None,
            feed_revision: None,
            view: None,
            pending: None,
            receipt: None,
            retirement: None,
            retirement_crossed: false,
            invalidation: None,
            retired_receipt: None,
            snapshot_version: None,
            next_version: INITIAL_PUBLICATION_VERSION,
            next_snapshot_version: INITIAL_SOURCE_VIEW_VERSION,
            revocation: None,
        })
    }

    /// Current lifecycle phase.
    #[must_use]
    pub const fn phase(&self) -> ControlPhase {
        self.phase
    }

    /// Current or invalidated helper lifetime, if one is known.
    #[must_use]
    pub const fn lifetime_id(&self) -> Option<LifetimeId> {
        self.lifetime
    }

    /// Current accepted feed revision, if known.
    #[must_use]
    pub const fn feed_revision(&self) -> Option<u64> {
        self.feed_revision
    }

    /// Adopted read-only metadata view, if one is current.
    #[must_use]
    pub const fn view(&self) -> Option<&MetadataView> {
        self.view.as_ref()
    }

    /// Current pending or bound publication tuple, if one is retained.
    #[must_use]
    pub fn current_tuple(&self) -> Option<Tuple> {
        match (self.pending, self.receipt) {
            (Some(pending), _) => Some(pending.tuple),
            (None, Some(receipt)) => Some(receipt.tuple),
            (None, None) => None,
        }
    }

    /// Active helper proof receipt, if the current tuple is bound.
    #[must_use]
    pub fn receipt(&self) -> Option<ReceiptId> {
        self.receipt.map(|receipt| receipt.receipt)
    }

    /// R1 source-view snapshot version of the current adopted view, if one is
    /// current.
    ///
    /// This is the tuple's `snapshot_version`; it is independent of the
    /// publication version and of the helper feed revision.
    #[must_use]
    pub const fn snapshot_version(&self) -> Option<u64> {
        self.snapshot_version
    }

    /// Publication version the next publication mint will allocate.
    #[must_use]
    pub const fn next_publication_version(&self) -> u64 {
        self.next_version
    }

    /// Why authority was revoked or closed, if it was.
    #[must_use]
    pub const fn revocation_reason(&self) -> Option<RevocationReason> {
        self.revocation
    }

    /// Whether authority is terminal.
    #[must_use]
    pub const fn is_closed(&self) -> bool {
        matches!(self.phase, ControlPhase::Closed)
    }

    /// Send `Establish` and validate the exact `Established` response.
    ///
    /// On success the session is bound to the launch nonce and the current
    /// lifetime is established. The initial `Projection` is read by
    /// [`Self::receive`].
    ///
    /// # Errors
    ///
    /// Returns [`PublicationControlError::NotReady`] when another record was
    /// already sent, or a fail-closed transport, codec, echo, or lifetime
    /// rejection. Every failure revokes authority.
    pub fn establish(&mut self) -> Result<LifetimeId, PublicationControlError> {
        self.require_phase(ControlPhase::Unestablished)?;
        self.send(RecordBody::Establish(self.expected_echo.clone()))?;

        let record = self.receive_record()?;
        self.validate_envelope(&record)?;
        let established = match record.body {
            RecordBody::Established(body) => body,
            RecordBody::Error(code) => return Err(self.peer_error(code)),
            body => return Err(self.unexpected(body.kind())),
        };
        Self::verify_echo(&self.expected_echo, &established.echo)
            .map_err(|error| self.fail(error, RevocationReason::EstablishmentMismatch))?;
        if established.lifetime_id == LifetimeId::ZERO {
            return Err(self.fail(
                PublicationControlError::LifetimeNotFresh,
                RevocationReason::ProtocolViolation,
            ));
        }

        self.lifetime = Some(established.lifetime_id);
        self.feed_revision = None;
        self.phase = ControlPhase::AwaitProjection;
        Ok(established.lifetime_id)
    }

    /// Read and process exactly one inbound record.
    ///
    /// `Projection`, `Ack`, `Bound`, and `Lifetime` advance the phase that
    /// expects them. `Invalidate` is legal in every established phase and an
    /// `Error` is always terminal. Any other kind revokes.
    ///
    /// # Errors
    ///
    /// Returns [`PublicationControlError::NotReady`] before establishment or
    /// [`PublicationControlError::Closed`] after revocation; every returned
    /// protocol or transport error revokes authority.
    pub fn receive(&mut self) -> Result<ControlEvent, PublicationControlError> {
        if self.phase == ControlPhase::Closed {
            return Err(PublicationControlError::Closed);
        }
        if self.phase == ControlPhase::Unestablished {
            return Err(PublicationControlError::NotReady { phase: self.phase });
        }

        let record = self.receive_record()?;
        self.validate_envelope(&record)?;
        match record.body {
            RecordBody::Error(code) => Err(self.peer_error(code)),
            RecordBody::Invalidate(body) => self.handle_invalidate(body),
            body => match self.phase {
                ControlPhase::AwaitProjection => self.handle_projection(body),
                ControlPhase::AwaitAck => self.handle_ack(body),
                ControlPhase::AwaitBound => self.handle_bound(body),
                ControlPhase::AwaitLifetime => self.handle_lifetime(body),
                phase => Err(self.unexpected_in(body.kind(), phase)),
            },
        }
    }

    /// Send `Publish` for the one pending tuple.
    ///
    /// # Errors
    ///
    /// Returns [`PublicationControlError::NotReady`] unless a projection was
    /// adopted, or a fail-closed send, schema, or digest rejection.
    pub fn send_publish(&mut self) -> Result<Tuple, PublicationControlError> {
        self.require_phase(ControlPhase::Ready)?;
        let ready = self.pending.and_then(|pending| {
            self.view.as_ref().map(|view| {
                let canonical = view.projection.canonical_bytes();
                (
                    pending.tuple,
                    view.projection.clone(),
                    canonical == view.canonical && Digest::of(&canonical) == view.digest,
                )
            })
        });
        let Some((tuple, payload, canonical_ok)) = ready else {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        };
        if !canonical_ok {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        }
        let Some(lifetime_id) = self.lifetime else {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        };
        let Some(feed_revision) = self.feed_revision else {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        };

        self.send(RecordBody::Publish(PublishBody {
            lifetime_id,
            feed_revision,
            tuple,
            payload,
        }))?;
        self.phase = ControlPhase::AwaitAck;
        Ok(tuple)
    }

    /// Send `Bind` with the exact retained acknowledgement.
    ///
    /// # Errors
    ///
    /// Returns [`PublicationControlError::NotReady`] unless `Ack` was
    /// accepted, or a fail-closed send rejection.
    pub fn send_bind(&mut self) -> Result<(), PublicationControlError> {
        self.require_phase(ControlPhase::AckAccepted)?;
        let (Some(pending), Some(ack_id), Some(lifetime_id), Some(feed_revision)) = (
            self.pending,
            self.pending.and_then(|pending| pending.ack_id),
            self.lifetime,
            self.feed_revision,
        ) else {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        };

        self.send(RecordBody::Bind(AckBody {
            lifetime_id,
            feed_revision,
            tuple: pending.tuple,
            ack_id,
        }))?;
        self.phase = ControlPhase::AwaitBound;
        Ok(())
    }

    /// Invalidate the current lifetime and wait for its replacement.
    ///
    /// `SourceMutation`, `Reset`, and `Supersession` send `Invalidate` and
    /// expect `Lifetime -> Projection`. `GrantLoss` and `Shutdown` send
    /// `Invalidate` and close authority without a replacement. `RegistryMutation`
    /// is helper-owned and is refused locally.
    ///
    /// A local invalidation is only legal with no publication transaction in
    /// flight; otherwise [`PublicationControlError::Busy`] is returned without
    /// sending or revoking anything.
    ///
    /// # Errors
    ///
    /// Returns a fail-closed rejection when the record cannot be sent or the
    /// current authority is not usable.
    pub fn invalidate(&mut self, reason: Reason) -> Result<(), PublicationControlError> {
        if reason == Reason::RegistryMutation {
            return Err(PublicationControlError::HelperOwnedInvalidationReason { reason });
        }
        match self.phase {
            ControlPhase::Ready | ControlPhase::AckAccepted | ControlPhase::Bound => {}
            ControlPhase::AwaitAck | ControlPhase::AwaitBound => {
                return Err(PublicationControlError::Busy { phase: self.phase });
            }
            phase => return Err(PublicationControlError::NotReady { phase }),
        }
        let Some(lifetime_id) = self.lifetime else {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        };
        let Some(feed_revision) = self.feed_revision else {
            return Err(self.fail(
                PublicationControlError::StaleAuthority,
                RevocationReason::ProtocolViolation,
            ));
        };

        self.send(RecordBody::Invalidate(InvalidateBody {
            lifetime_id,
            feed_revision,
            reason,
        }))?;
        self.clear_publication();
        if matches!(reason, Reason::GrantLoss | Reason::Shutdown) {
            self.revoke(RevocationReason::PeerWithdrewAuthority);
            return Ok(());
        }
        self.invalidation = Some(InvalidationWait {
            feed_revision,
            reason,
            crossed_consumed: false,
        });
        self.phase = ControlPhase::AwaitLifetime;
        Ok(())
    }

    /// Close authority locally without writing another record.
    ///
    /// Terminal and idempotent. The transport is dropped, which closes the
    /// authenticated session; no record is retried on a replacement stream.
    pub fn close(&mut self) {
        if self.phase == ControlPhase::Closed {
            return;
        }
        self.revoke(RevocationReason::LocalClose);
    }

    fn require_phase(&self, expected: ControlPhase) -> Result<(), PublicationControlError> {
        if self.phase == expected {
            Ok(())
        } else if self.phase == ControlPhase::Closed {
            Err(PublicationControlError::Closed)
        } else {
            Err(PublicationControlError::NotReady { phase: self.phase })
        }
    }

    fn send(&mut self, body: RecordBody) -> Result<(), PublicationControlError> {
        if self.phase == ControlPhase::Closed {
            return Err(PublicationControlError::Closed);
        }
        let sequence = match next_expected_sequence(self.out_sequence) {
            Ok(sequence) => sequence,
            Err(_) => {
                return Err(self.fail(
                    PublicationControlError::VersionExhausted,
                    RevocationReason::ResourceLimit,
                ));
            }
        };
        let record = ControlRecord {
            sender: Sender::Core,
            sequence,
            session_id: self.binding.launch_nonce,
            body,
        };
        let Some(io) = self.io.as_mut() else {
            return Err(PublicationControlError::Closed);
        };
        match io.send(&record) {
            Ok(()) => {
                self.out_sequence = sequence;
                Ok(())
            }
            Err(error) => Err(self.fail(
                PublicationControlError::Transport(error),
                RevocationReason::ControlTransport,
            )),
        }
    }

    fn receive_record(&mut self) -> Result<ControlRecord, PublicationControlError> {
        let Some(io) = self.io.as_mut() else {
            return Err(PublicationControlError::Closed);
        };
        match io.receive() {
            Ok(record) => Ok(record),
            Err(error) => {
                let reason = match &error {
                    ControlIoError::Io(_)
                    | ControlIoError::Closed
                    | ControlIoError::TruncatedPrefix { .. }
                    | ControlIoError::TruncatedBody { .. }
                    | ControlIoError::WriteZero
                    | ControlIoError::UnsupportedPlatform => RevocationReason::ControlTransport,
                    ControlIoError::AllocationFailed { .. } => RevocationReason::ResourceLimit,
                    ControlIoError::ZeroLength
                    | ControlIoError::FrameTooLarge
                    | ControlIoError::FrameShorterThanHeader { .. }
                    | ControlIoError::Codec(_) => RevocationReason::ProtocolViolation,
                };
                Err(self.fail(PublicationControlError::Transport(error), reason))
            }
        }
    }

    fn validate_envelope(&mut self, record: &ControlRecord) -> Result<(), PublicationControlError> {
        if record.sender != Sender::Helper {
            return Err(self.fail(
                PublicationControlError::UnexpectedSender {
                    sender: record.sender,
                },
                RevocationReason::ProtocolViolation,
            ));
        }
        if validate_session(self.binding.launch_nonce, record.session_id).is_err() {
            return Err(self.fail(
                PublicationControlError::SessionMismatch,
                RevocationReason::ProtocolViolation,
            ));
        }
        if validate_incoming_sequence(self.in_sequence, record.sequence).is_err() {
            return Err(self.fail(
                PublicationControlError::SequenceMismatch,
                RevocationReason::ProtocolViolation,
            ));
        }
        self.in_sequence = record.sequence;
        Ok(())
    }

    fn handle_projection(
        &mut self,
        body: RecordBody,
    ) -> Result<ControlEvent, PublicationControlError> {
        let ProjectionBody {
            lifetime_id,
            feed_revision,
            payload,
        } = match body {
            RecordBody::Projection(body) => body,
            body => return Err(self.unexpected(body.kind())),
        };
        if self.lifetime != Some(lifetime_id) {
            return Err(self.stale());
        }
        if feed_revision == 0 {
            return Err(self.stale());
        }
        if let Some(expected) = self.feed_revision {
            if feed_revision != expected {
                return Err(self.stale());
            }
        }
        if self.view.is_some() || self.pending.is_some() {
            return Err(self.stale());
        }

        let canonical = payload.canonical_bytes();
        let digest = Digest::of(&canonical);
        let publication_version = self.allocate_publication_version()?;
        let snapshot_version = self.allocate_source_view_version()?;
        let tuple = self
            .mint_tuple(publication_version, snapshot_version, digest)
            .map_err(|error| {
                self.fail(
                    PublicationControlError::Record(error),
                    RevocationReason::ProtocolViolation,
                )
            })?;

        self.snapshot_version = Some(snapshot_version);
        self.feed_revision = Some(feed_revision);
        self.view = Some(MetadataView {
            projection: payload,
            canonical,
            digest,
            feed_revision,
        });
        self.pending = Some(PendingPublication {
            tuple,
            ack_id: None,
        });
        self.phase = ControlPhase::Ready;
        Ok(ControlEvent::ProjectionAdopted {
            lifetime_id,
            feed_revision,
            snapshot_version,
            publication_version,
        })
    }

    /// Mint the next Core publication version.
    ///
    /// This counter advances for every publication attempt and is independent
    /// of the R1 source-view snapshot version.
    fn allocate_publication_version(&mut self) -> Result<u64, PublicationControlError> {
        let version = self.next_version;
        let Some(next) = version.checked_add(1) else {
            return Err(self.fail(
                PublicationControlError::VersionExhausted,
                RevocationReason::ResourceLimit,
            ));
        };
        self.next_version = next;
        Ok(version)
    }

    /// Mint the next Core source-view snapshot version.
    ///
    /// The counter advances only when Core adopts a replacement source view.
    /// In this state machine every `Projection` in `AwaitProjection` is such a
    /// replacement: the initial adoption mints `1`, and each rotation
    /// (source mutation, registry mutation, reset, or supersession) mints the
    /// next value. A publication-only re-mint would not call this method.
    fn allocate_source_view_version(&mut self) -> Result<u64, PublicationControlError> {
        let version = self.next_snapshot_version;
        let Some(next) = version.checked_add(1) else {
            return Err(self.fail(
                PublicationControlError::VersionExhausted,
                RevocationReason::ResourceLimit,
            ));
        };
        self.next_snapshot_version = next;
        Ok(version)
    }

    /// Build one tuple from the two independent Core-owned versions.
    fn mint_tuple(
        &self,
        publication_version: u64,
        snapshot_version: u64,
        digest: Digest,
    ) -> Result<Tuple, ControlError> {
        Tuple::new(
            PublicationId::from_parts(self.binding.launch_nonce, publication_version),
            snapshot_version,
            digest,
        )
    }

    fn handle_ack(&mut self, body: RecordBody) -> Result<ControlEvent, PublicationControlError> {
        let body = match body {
            RecordBody::Ack(body) => body,
            body => return Err(self.unexpected(body.kind())),
        };
        let Some(pending) = self.pending else {
            return Err(self.stale());
        };
        if pending.ack_id.is_some()
            || self.lifetime != Some(body.lifetime_id)
            || self.feed_revision != Some(body.feed_revision)
            || pending.tuple != body.tuple
        {
            return Err(self.stale());
        }
        if body.ack_id == AckId::ZERO {
            return Err(self.fail(
                PublicationControlError::IdentifierNotFresh,
                RevocationReason::ProtocolViolation,
            ));
        }

        if let Some(pending) = self.pending.as_mut() {
            pending.ack_id = Some(body.ack_id);
        }
        self.phase = ControlPhase::AckAccepted;
        Ok(ControlEvent::PublicationAcknowledged {
            ack_id: body.ack_id,
        })
    }

    fn handle_bound(&mut self, body: RecordBody) -> Result<ControlEvent, PublicationControlError> {
        let body = match body {
            RecordBody::Bound(body) => body,
            body => return Err(self.unexpected(body.kind())),
        };
        let Some(pending) = self.pending else {
            return Err(self.stale());
        };
        let Some(ack_id) = pending.ack_id else {
            return Err(self.stale());
        };
        if self.lifetime != Some(body.lifetime_id)
            || self.feed_revision != Some(body.feed_revision)
            || pending.tuple != body.tuple
        {
            return Err(self.stale());
        }
        if body.receipt == ReceiptId::ZERO
            || body.receipt.as_bytes() == ack_id.as_bytes()
            || self.retired_receipt == Some(body.receipt)
        {
            return Err(self.fail(
                PublicationControlError::IdentifierNotFresh,
                RevocationReason::ProtocolViolation,
            ));
        }

        self.receipt = Some(ActiveReceipt {
            tuple: pending.tuple,
            receipt: body.receipt,
        });
        self.pending = None;
        self.phase = ControlPhase::Bound;
        Ok(ControlEvent::PublicationBound {
            tuple: pending.tuple,
            receipt: body.receipt,
        })
    }

    fn handle_invalidate(
        &mut self,
        body: InvalidateBody,
    ) -> Result<ControlEvent, PublicationControlError> {
        if body.feed_revision == 0 {
            return Err(self.stale());
        }
        let current_matches = self.lifetime == Some(body.lifetime_id)
            && self
                .feed_revision
                .is_none_or(|revision| revision == body.feed_revision);
        if current_matches {
            if matches!(body.reason, Reason::GrantLoss | Reason::Shutdown) {
                self.revoke(RevocationReason::PeerWithdrewAuthority);
                return Ok(ControlEvent::AuthorityClosed {
                    reason: body.reason,
                });
            }
            if self.phase == ControlPhase::AwaitLifetime {
                let Some(wait) = self.invalidation.as_mut() else {
                    return Err(self.stale());
                };
                if wait.crossed_consumed {
                    return Err(self.stale());
                }
                wait.crossed_consumed = true;
                return Ok(ControlEvent::Invalidated {
                    lifetime_id: body.lifetime_id,
                    feed_revision: body.feed_revision,
                    reason: body.reason,
                    correlation_only: true,
                });
            }

            self.feed_revision = Some(body.feed_revision);
            self.clear_publication();
            self.invalidation = Some(InvalidationWait {
                feed_revision: body.feed_revision,
                reason: body.reason,
                crossed_consumed: false,
            });
            self.phase = ControlPhase::AwaitLifetime;
            return Ok(ControlEvent::Invalidated {
                lifetime_id: body.lifetime_id,
                feed_revision: body.feed_revision,
                reason: body.reason,
                correlation_only: false,
            });
        }

        if self.retirement
            == Some(RetiredLifetime {
                lifetime_id: body.lifetime_id,
                feed_revision: body.feed_revision,
            })
        {
            if self.retirement_crossed {
                return Err(self.stale());
            }
            self.retirement_crossed = true;
            if matches!(body.reason, Reason::GrantLoss | Reason::Shutdown) {
                self.revoke(RevocationReason::PeerWithdrewAuthority);
                return Ok(ControlEvent::AuthorityClosed {
                    reason: body.reason,
                });
            }
            return Ok(ControlEvent::Invalidated {
                lifetime_id: body.lifetime_id,
                feed_revision: body.feed_revision,
                reason: body.reason,
                correlation_only: true,
            });
        }

        Err(self.stale())
    }

    fn handle_lifetime(
        &mut self,
        body: RecordBody,
    ) -> Result<ControlEvent, PublicationControlError> {
        let LifetimeBody {
            lifetime_id,
            feed_revision,
        } = match body {
            RecordBody::Lifetime(body) => body,
            body => return Err(self.unexpected(body.kind())),
        };
        let Some(wait) = self.invalidation else {
            return Err(self.stale());
        };
        let Some(previous) = self.lifetime else {
            return Err(self.stale());
        };
        let previous_revision = self.feed_revision.unwrap_or(wait.feed_revision);
        let repeats_retired = self
            .retirement
            .is_some_and(|retired| retired.lifetime_id == lifetime_id);
        if feed_revision == 0
            || lifetime_id == LifetimeId::ZERO
            || lifetime_id == previous
            || repeats_retired
        {
            return Err(self.fail(
                PublicationControlError::LifetimeNotFresh,
                RevocationReason::ProtocolViolation,
            ));
        }
        let expected_revision = match wait.reason {
            Reason::RegistryMutation => previous_revision.checked_add(1),
            Reason::SourceMutation | Reason::Reset | Reason::Supersession => {
                Some(previous_revision)
            }
            Reason::GrantLoss | Reason::Shutdown => None,
        };
        if expected_revision != Some(feed_revision) {
            return Err(self.stale());
        }

        self.retirement = Some(RetiredLifetime {
            lifetime_id: previous,
            feed_revision: previous_revision,
        });
        // Carry the once-only crossed-invalidation allowance into the retired
        // window. If it was already consumed while waiting for this lifetime,
        // replaying the predecessor after the rotation must still be refused.
        self.retirement_crossed = wait.crossed_consumed;
        self.lifetime = Some(lifetime_id);
        self.feed_revision = Some(feed_revision);
        self.clear_publication();
        self.invalidation = None;
        self.phase = ControlPhase::AwaitProjection;
        Ok(ControlEvent::LifetimeRotated {
            previous,
            lifetime_id,
            feed_revision,
        })
    }

    fn verify_echo(
        expected: &EstablishmentEcho,
        received: &EstablishmentEcho,
    ) -> Result<(), PublicationControlError> {
        let field = if received.bootstrap_format_version != expected.bootstrap_format_version {
            "bootstrap_format_version"
        } else if received.control_protocol_version != expected.control_protocol_version {
            "control_protocol_version"
        } else if received.core_instance_nonce != expected.core_instance_nonce {
            "core_instance_nonce"
        } else if received.launch_nonce != expected.launch_nonce {
            "launch_nonce"
        } else if received.component_name != expected.component_name {
            "component_name"
        } else if received.descriptor_version != expected.descriptor_version {
            "descriptor_version"
        } else if received.executable_name != expected.executable_name {
            "executable_name"
        } else if received.executable_sha256 != expected.executable_sha256 {
            "executable_sha256"
        } else if received.component_protocol_version != expected.component_protocol_version {
            "component_protocol_version"
        } else if received.control_channel_nonce != expected.control_channel_nonce {
            "control_channel_nonce"
        } else if received.data_channel_nonce != expected.data_channel_nonce {
            "data_channel_nonce"
        } else if received.delegation_purpose != expected.delegation_purpose {
            "delegation_purpose"
        } else if received.control_profile != expected.control_profile {
            "control_profile"
        } else if received.key_material_profile != expected.key_material_profile {
            "key_material_profile"
        } else if received.key_type != expected.key_type {
            "key_type"
        } else if received.core_leaf_digest != expected.core_leaf_digest {
            "core_leaf_digest"
        } else if received.helper_leaf_digest != expected.helper_leaf_digest {
            "helper_leaf_digest"
        } else {
            return Ok(());
        };
        Err(PublicationControlError::EstablishmentMismatch { field })
    }

    fn clear_publication(&mut self) {
        if let Some(receipt) = self.receipt.take() {
            self.retired_receipt = Some(receipt.receipt);
        }
        self.view = None;
        self.pending = None;
        self.snapshot_version = None;
    }

    fn stale(&mut self) -> PublicationControlError {
        self.fail(
            PublicationControlError::StaleAuthority,
            RevocationReason::ProtocolViolation,
        )
    }

    fn unexpected(&mut self, kind: Kind) -> PublicationControlError {
        self.unexpected_in(kind, self.phase)
    }

    fn unexpected_in(&mut self, kind: Kind, phase: ControlPhase) -> PublicationControlError {
        self.fail(
            PublicationControlError::UnexpectedRecord { kind, phase },
            RevocationReason::ProtocolViolation,
        )
    }

    fn peer_error(&mut self, code: ErrorCode) -> PublicationControlError {
        self.fail(
            PublicationControlError::PeerError { code },
            RevocationReason::PeerError,
        )
    }

    fn fail(
        &mut self,
        error: PublicationControlError,
        reason: RevocationReason,
    ) -> PublicationControlError {
        if self.phase != ControlPhase::Closed {
            self.revoke(reason);
        }
        error
    }

    fn revoke(&mut self, reason: RevocationReason) {
        self.phase = ControlPhase::Closed;
        if self.revocation.is_none() {
            self.revocation = Some(reason);
        }
        self.clear_authority();
    }

    fn clear_authority(&mut self) {
        self.lifetime = None;
        self.feed_revision = None;
        self.view = None;
        self.pending = None;
        self.receipt = None;
        self.retirement = None;
        self.retirement_crossed = false;
        self.invalidation = None;
        self.retired_receipt = None;
        self.snapshot_version = None;
        // Dropping the transport closes the authenticated session.
        self.io = None;
    }
}

impl<T> fmt::Debug for PublicationControl<T> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("PublicationControl")
            .field("phase", &self.phase)
            .field("established", &self.lifetime.is_some())
            .field("pending_publication", &self.pending.is_some())
            .field("active_receipt", &self.receipt.is_some())
            .field("closed", &matches!(self.phase, ControlPhase::Closed))
            .field("revocation", &self.revocation)
            .finish_non_exhaustive()
    }
}
