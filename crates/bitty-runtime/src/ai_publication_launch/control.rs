//! Core-side provider-publication control driver.
//!
//! This module is the Core half of the authenticated control session the Bitty
//! AI draft *Authenticated provider publication* specifies. It sits above
//! [`EstablishedControl`](super::EstablishedControl), consumes the pure record
//! contract from `bitty-ipc-api`'s `provider_publication` module, and drives
//! exactly the sequence below:
//!
//! 1. `Establish` -> `Established`, validating every non-secret echo field and
//!    binding the session to the launch nonce.
//! 2. `Projection`, adopting one bounded, canonicalized read-only metadata
//!    view and allocating exactly one pending publication tuple.
//! 3. `Publish` -> `Ack` -> `Bind` -> `Bound`, with exact tuple, lifetime,
//!    revision, and acknowledgement matching and a single retained receipt.
//! 4. `Invalidate` / `Lifetime` / `Projection` rotation, retaining one
//!    immediately retired predecessor for a single crossed invalidation.
//!
//! Every mismatch, duplicate, stale, cross-session, out-of-order, framing, or
//! transport failure revokes authority and closes the driver. Local caller
//! mistakes that send nothing ([`PublicationControlError::NotReady`] and
//! [`PublicationControlError::Busy`]) are reported without revoking.
//!
//! Core owns two independent monotonic counters. The publication version lives
//! in the tuple's `PublicationId` and advances for every publication attempt.
//! The tuple's `snapshot_version` is the R1 source-view snapshot version: `1`
//! for the first adopted Projection, then one greater each time Core replaces
//! its accepted source view (every later rotation Projection, including reset
//! and source-mutation rotations). It is never inferred from the helper feed
//! revision, from the publication version, or from the generic IPC
//! `snapshot_version` field, and it does not advance merely because the
//! publication version does. Neither counter resets on rotation, and the
//! per-direction record sequence never resets.
//!
//! # Deliberately out of scope
//!
//! Strict provider publication stays disabled. There is no `Admit`,
//! data-channel reservation, `ai.provider_list` handler, `ai_helper` wiring,
//! provider/credential/handler contact, listener, socket, thread, or clock.
//! The caller owns every deadline and the bounded record queue, and it owns
//! the transport: dropping the driver drops the authenticated session. Core
//! never delays revocation on a diagnostic write, so a failed driver emits no
//! `Error` record; it closes and reports the local cause.
//!
//! The driver is behind the default-off `publication-control` feature. On
//! non-Unix platforms [`AuthenticatedControl::new`] fails closed with
//! [`PublicationControlError::UnsupportedPlatform`]; the state machine itself
//! still compiles and is testable with any [`ControlRecordIo`] implementation.

