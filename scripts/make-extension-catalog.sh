#!/usr/bin/env bash
# make-extension-catalog.sh — generate, verify, or publish `extensions/catalog.v1`.
#
# The catalog is a digest index over the published extension payloads:
#
#   schema 1
#   extension <name> <version> <target> <sha256>
#
# Every record is derived from a published `SHA256SUMS` object and every
# artifact is re-hashed before a record is emitted, so the catalog cannot
# disagree with the payload it selects. Discovery reads the R2 bucket through
# the Cloudflare API (the CDN has no directory listing); `--source-dir` reads
# the same `<name>/<version>/SHA256SUMS` layout locally for hermetic tests.
#
# Modes:
#   (default)  print the canonical catalog to stdout or --output
#   --check    compare the canonical bytes with the live object (drift gate)
#   --publish  upload, read the object back from R2, then verify the CDN URL
#
# Publishing is append-only for published versions: a catalog record that is
# no longer discoverable is refused unless `--allow-yank` is passed, because
# removing an entry is a yank decision. Versioned payload prefixes stay
# immutable; only `catalog.v1` is mutable metadata.
#
# Environment (live discovery and publish):
#   CLOUDFLARE_API_TOKEN, CLOUDFLARE_ACCOUNT_ID, R2_BUCKET (default bitty)
#   WRANGLER_BIN (default wrangler), BITTY_CDN_BASE_URL, R2_PREFIX
set -euo pipefail

readonly DEFAULT_BASE_URL="https://cdn.bitty.run"
readonly DEFAULT_API_BASE="https://api.cloudflare.com/client/v4"
readonly DEFAULT_BUCKET="bitty"
readonly DEFAULT_PREFIX="extensions"
readonly CATALOG_KEY="catalog.v1"
readonly CATALOG_CACHE_CONTROL="public, max-age=300, must-revalidate"
readonly CATALOG_CONTENT_TYPE="text/plain; charset=utf-8"
readonly PUBLISH_READBACK_ATTEMPTS=12
readonly PUBLISH_READBACK_DELAY_SECS=5
readonly CATALOG_HEADER='# bitty extension catalog v1
# Generated by scripts/make-extension-catalog.sh from published SHA256SUMS.
# Do not edit by hand; regenerate and republish after any extension release.
schema 1'

BASE_URL="${BITTY_CDN_BASE_URL:-$DEFAULT_BASE_URL}"
API_BASE="${BITTY_API_BASE_URL:-$DEFAULT_API_BASE}"
BUCKET="${R2_BUCKET:-$DEFAULT_BUCKET}"
PREFIX="${R2_PREFIX:-$DEFAULT_PREFIX}"
WRANGLER_BIN="${WRANGLER_BIN:-wrangler}"

SOURCE_DIR=""
OUTPUT=""
MODE="generate"
ALLOW_EMPTY=0
ALLOW_YANK=0
SCRATCH=""

usage() {
  cat <<'EOF'
usage: scripts/make-extension-catalog.sh [options]

  --source-dir DIR  read extensions from DIR instead of the R2 bucket
                    (DIR/<name>/<version>/SHA256SUMS plus tarballs)
  --output FILE     write the catalog to FILE (default stdout)
  --check           compare the canonical catalog with the live object
  --publish         upload and read back the catalog (requires credentials)
  --allow-empty     permit a schema-only catalog (default: refuse)
  --allow-yank      permit dropping a live catalog record (explicit yank)
  --help            show this help

Live discovery uses the Cloudflare API:
  CLOUDFLARE_API_TOKEN, CLOUDFLARE_ACCOUNT_ID, R2_BUCKET (default bitty)
EOF
}

die() {
  printf 'make-extension-catalog: ERROR: %s\n' "$1" >&2
  exit 1
}

note() {
  printf 'make-extension-catalog: %s\n' "$1" >&2
}

cleanup() {
  if [[ -n "$SCRATCH" && -d "$SCRATCH" ]]; then
    rm -rf -- "$SCRATCH"
  fi
}
trap cleanup EXIT

while (($# > 0)); do
  case "$1" in
  --source-dir)
    [[ $# -ge 2 ]] || die "--source-dir needs a value"
    SOURCE_DIR="$2"
    shift 2
    ;;
  --output)
    [[ $# -ge 2 ]] || die "--output needs a value"
    OUTPUT="$2"
    shift 2
    ;;
  --check)
    MODE="check"
    shift
    ;;
  --publish)
    MODE="publish"
    shift
    ;;
  --allow-empty)
    ALLOW_EMPTY=1
    shift
    ;;
  --allow-yank)
    ALLOW_YANK=1
    shift
    ;;
  --help | -h)
    usage
    exit 0
    ;;
  *) die "unknown argument: $1 (try --help)" ;;
  esac
done

[[ "$MODE" == "generate" || -z "$OUTPUT" ]] || die "--output is only valid in generate mode"
[[ "$MODE" == "publish" || "$ALLOW_YANK" == "0" ]] || die "--allow-yank is only valid with --publish"

valid_name() {
  [[ "$1" =~ ^[a-z][a-z0-9-]{0,31}$ ]]
}

valid_version() {
  [[ "$1" =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$ ]]
}

valid_target() {
  [[ "$1" =~ ^[a-z0-9_]+(-[a-z0-9_]+)+$ ]]
}

sha256_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d' ' -f1
  elif command -v shasum >/dev/null 2>&1; then
    shasum -a 256 "$1" | cut -d' ' -f1
  else
    die "no sha256 tool found (need sha256sum or shasum)"
  fi
}

need_curl() {
  command -v curl >/dev/null 2>&1 || die "curl is required"
}

fetch() { # URL DEST
  local url="$1" dest="$2" status
  if ! status="$(curl -sS --proto '=https' --tlsv1.2 -L -o "$dest" -w '%{http_code}' "$url")"; then
    die "cannot fetch $url (transport failure)"
  fi
  [[ "$status" == "200" ]] || die "cannot fetch $url (HTTP $status)"
}

fetch_api() { # URL DEST
  local url="$1" dest="$2" status
  if ! status="$(curl -sS --proto '=https' --tlsv1.2 -L \
    -H "Authorization: Bearer $CLOUDFLARE_API_TOKEN" \
    -o "$dest" -w '%{http_code}' "$url")"; then
    die "cannot reach the Cloudflare API (transport failure)"
  fi
  [[ "$status" == "200" ]] || die "Cloudflare API returned HTTP $status"
}

fetch_optional() { # URL DEST (404 -> return 1)
  local url="$1" dest="$2" status
  status="$(curl -sS --proto '=https' --tlsv1.2 -L -o "$dest" -w '%{http_code}' "$url")" ||
    die "cannot fetch $url (transport failure)"
  case "$status" in
  200) return 0 ;;
  404) return 1 ;;
  *) die "cannot fetch $url (HTTP $status)" ;;
  esac
}

validate_base_url() {
  [[ "$BASE_URL" =~ ^https://[A-Za-z0-9.-]+(:[0-9]+)?(/[A-Za-z0-9._~/-]*)?$ ]] ||
    die "base URL must be https://host[:port][/path] (got $BASE_URL)"
}

discover_source() {
  [[ -d "$SOURCE_DIR" ]] || die "source directory does not exist: $SOURCE_DIR"
  find "$SOURCE_DIR" -mindepth 3 -maxdepth 3 -type f -name SHA256SUMS | LC_ALL=C sort
}

discover_live() {
  need_curl
  [[ -n "${CLOUDFLARE_API_TOKEN:-}" ]] || die "CLOUDFLARE_API_TOKEN is required for live discovery"
  [[ -n "${CLOUDFLARE_ACCOUNT_ID:-}" ]] || die "CLOUDFLARE_ACCOUNT_ID is required for live discovery"
  local listing="$SCRATCH/objects.txt" cursor="" page
  : >"$listing"
  while :; do
    page="$SCRATCH/objects-page.json"
    fetch_api "$API_BASE/accounts/$CLOUDFLARE_ACCOUNT_ID/r2/buckets/$BUCKET/objects?prefix=$PREFIX/&per_page=1000$cursor" "$page"
    jq -e '.success == true and (.result | type == "array")' "$page" >/dev/null ||
      die "Cloudflare API listing failed (see $page)"
    jq -r '.result[].key' "$page" >>"$listing"
    cursor="$(jq -r '.result_info.cursor // empty' "$page")"
    [[ -n "$cursor" ]] || break
    cursor="&cursor=$cursor"
  done
  LC_ALL=C sort -u "$listing"
}

emit_records() { # NAME VERSION MANIFEST RECORDS
  local name="$1" version="$2" manifest="$3" records="$4" line digest file target artifact actual
  local seen=" " major minor patch version_key
  IFS='.' read -r major minor patch <<<"$version"
  version_key="$(printf '%010d.%010d.%010d' "$major" "$minor" "$patch")"
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%$'\r'}"
    [[ -z "${line//[[:space:]]/}" ]] && continue
    [[ "$line" =~ ^([0-9a-fA-F]{64})[[:space:]]{1,2}\*?([^[:space:]]+)$ ]] ||
      die "malformed SHA256SUMS line for $name $version: $line"
    digest="${BASH_REMATCH[1],,}"
    file="${BASH_REMATCH[2]}"
    [[ "$file" == *.tar.gz ]] || die "SHA256SUMS entry is not a tarball: $file"
    target="${file%.tar.gz}"
    valid_target "$target" || die "invalid target triple in SHA256SUMS: $target"
    [[ "$seen" != *" $file "* ]] || die "duplicate SHA256SUMS entry: $file"
    seen+=" $file "
    if [[ -n "$SOURCE_DIR" ]]; then
      artifact="$SOURCE_DIR/$name/$version/$file"
      [[ -f "$artifact" ]] || die "missing artifact: $artifact"
    else
      artifact="$SCRATCH/payload/$name/$version/$file"
      mkdir -p "$(dirname "$artifact")"
      fetch "$BASE_URL/$PREFIX/$name/$version/$file" "$artifact"
    fi
    actual="$(sha256_file "$artifact")"
    [[ "$actual" == "$digest" ]] ||
      die "digest mismatch for $name $version $target: SHA256SUMS says $digest, artifact is $actual"
    printf '%s\t%s\t%s\t%s\n' \
      "$name" "$version_key" "$target" "extension $name $version $target $digest" >>"$records"
  done <"$manifest"
}

build_catalog() { # OUTPUT
  local output="$1" keys name version key manifest records sorted
  keys="$SCRATCH/discovered.txt"
  records="$SCRATCH/records.txt"
  : >"$records"

  if [[ -n "$SOURCE_DIR" ]]; then
    discover_source >"$keys"
  else
    discover_live >"$SCRATCH/all-keys.txt"
    grep -E "^$PREFIX/[a-z][a-z0-9-]{0,31}/[0-9]+\.[0-9]+\.[0-9]+/SHA256SUMS$" \
      "$SCRATCH/all-keys.txt" >"$keys" || true
  fi

  while IFS= read -r key || [[ -n "$key" ]]; do
    [[ -n "$key" ]] || continue
    key="${key#"$SOURCE_DIR"/}"
    key="${key#"$PREFIX"/}"
    key="${key%/SHA256SUMS}"
    name="${key%%/*}"
    version="${key##*/}"
    [[ "$name" != "$key" ]] || die "cannot derive name/version from discovery entry: $key"
    valid_name "$name" || die "invalid extension name in discovery: $name"
    valid_version "$version" || die "invalid extension version in discovery: $version"
    if [[ -n "$SOURCE_DIR" ]]; then
      manifest="$SOURCE_DIR/$key/SHA256SUMS"
      [[ -f "$manifest" ]] || die "missing manifest: $manifest"
    else
      manifest="$SCRATCH/payload/$name/$version/SHA256SUMS"
      mkdir -p "$(dirname "$manifest")"
      fetch "$BASE_URL/$PREFIX/$key/SHA256SUMS" "$manifest"
    fi
    emit_records "$name" "$version" "$manifest" "$records"
  done <"$keys"

  if [[ ! -s "$records" && "$ALLOW_EMPTY" == "0" ]]; then
    die "no published extensions found under $PREFIX/ (refusing to emit an empty catalog)"
  fi

  sorted="$SCRATCH/records.sorted"
  LC_ALL=C sort -t$'\t' -k1,1 -k2,2 -k3,3 "$records" >"$sorted"

  {
    printf '%s\n' "$CATALOG_HEADER"
    cut -f4 "$sorted"
  } >"$output"
}

main() {
  local output live live_records generated_records remote attempt
  if [[ -n "$SOURCE_DIR" ]]; then
    SOURCE_DIR="$(cd -- "$SOURCE_DIR" && pwd)"
  fi
  if [[ -z "$SOURCE_DIR" && ("$MODE" == "check" || "$MODE" == "publish") ]]; then
    need_curl
  fi
  if [[ "$MODE" == "publish" ]]; then
    [[ -n "${CLOUDFLARE_API_TOKEN:-}" ]] || die "CLOUDFLARE_API_TOKEN is required to publish"
    [[ -n "${CLOUDFLARE_ACCOUNT_ID:-}" ]] || die "CLOUDFLARE_ACCOUNT_ID is required to publish"
    command -v "$WRANGLER_BIN" >/dev/null 2>&1 || die "wrangler is required to publish"
  fi
  if [[ -z "$SOURCE_DIR" ]]; then
    validate_base_url
    need_curl
  fi

  mkdir -p "${TMPDIR:-/tmp}/bitty"
  SCRATCH="$(mktemp -d "${TMPDIR:-/tmp}/bitty/make-extension-catalog.XXXXXX")"
  output="$SCRATCH/catalog.v1"

  build_catalog "$output"

  if [[ "$MODE" == "generate" ]]; then
    if [[ -n "$OUTPUT" ]]; then
      mkdir -p "$(dirname -- "$OUTPUT")"
      cp -- "$output" "$OUTPUT"
      note "wrote $OUTPUT"
    else
      cat -- "$output"
    fi
    return 0
  fi

  if [[ "$MODE" == "check" ]]; then
    live="$SCRATCH/live.v1"
    if ! curl -fsS --proto '=https' --tlsv1.2 -L -o "$live" "$BASE_URL/$PREFIX/$CATALOG_KEY"; then
      die "live catalog is not fetchable at $BASE_URL/$PREFIX/$CATALOG_KEY"
    fi
    if cmp -s "$output" "$live"; then
      note "catalog is in sync with published SHA256SUMS"
      return 0
    fi
    printf 'make-extension-catalog: catalog drift detected (live object differs from generated bytes)\n' >&2
    diff -u "$live" "$output" >&2 || true
    die "republish with --publish after reviewing the diff"
  fi

  # Publish: append-only guard against silently dropping live records.
  live="$SCRATCH/live.v1"
  if fetch_optional "$BASE_URL/$PREFIX/$CATALOG_KEY" "$live"; then
    live_records="$SCRATCH/live.records"
    generated_records="$SCRATCH/generated.records"
    awk '$1 == "extension" { print $2, $3, $4, $5 }' "$live" | LC_ALL=C sort >"$live_records"
    awk '$1 == "extension" { print $2, $3, $4, $5 }' "$output" | LC_ALL=C sort >"$generated_records"
    if [[ "$ALLOW_YANK" == "0" ]] && comm -23 "$live_records" "$generated_records" | grep -q .; then
      comm -23 "$live_records" "$generated_records" >&2
      die "live catalog records are missing from the generated catalog (explicit yank; pass --allow-yank)"
    fi
  else
    note "live catalog is absent; creating it"
  fi

  "$WRANGLER_BIN" r2 object put "$BUCKET/$PREFIX/$CATALOG_KEY" \
    --file "$output" \
    --content-type "$CATALOG_CONTENT_TYPE" \
    --cache-control "$CATALOG_CACHE_CONTROL" \
    --remote -y >/dev/null
  note "uploaded $BUCKET/$PREFIX/$CATALOG_KEY"

  remote="$SCRATCH/remote.v1"
  "$WRANGLER_BIN" r2 object get "$BUCKET/$PREFIX/$CATALOG_KEY" --remote --pipe >"$remote"
  cmp -s "$output" "$remote" || die "origin read-back differs from the uploaded catalog"
  note "origin read-back verified (sha256 $(sha256_file "$remote"))"

  for ((attempt = 1; attempt <= PUBLISH_READBACK_ATTEMPTS; attempt++)); do
    if curl -fsS --proto '=https' --tlsv1.2 -L -o "$remote" "$BASE_URL/$PREFIX/$CATALOG_KEY" &&
      cmp -s "$output" "$remote"; then
      note "CDN read-back verified: $BASE_URL/$PREFIX/$CATALOG_KEY"
      return 0
    fi
    sleep "$PUBLISH_READBACK_DELAY_SECS"
  done
  die "CDN still serves a different object after $PUBLISH_READBACK_ATTEMPTS attempts (check the edge cache)"
}

main "$@"
